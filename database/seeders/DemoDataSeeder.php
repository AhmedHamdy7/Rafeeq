/**
 * Data broad enough that the mobile team can open any screen and find something in it.
 *
 * 🔴 Why this is separate from `DatabaseSeeder` rather than folded into it. That one builds the
 * Bible's reference scenario — ONE driver, ONE passenger, ONE commute — and it is right to stay
 * that way: it is the story the documentation describes and the tests reason about. But one commute
 * means search returns a single result, nobody has a rating, and half the screens render an empty
 * state. A client developer cannot tell "the endpoint works and the list is empty" from "the
 * endpoint is broken", and will spend a day on the wrong one.
 *
 * So this runs that scenario first and then adds breadth around it:
 *
 *   · five more approved drivers with published commutes on the same corridor, at different
 *     prices, departure times, seat counts and audiences — so search ranks a real list and the
 *     score breakdown on screen 12 has something to break down
 *   · a fortnight of scheduled days for every one of them, generated by the REAL command rather
 *     than hand-written rows, so the horizon, the booking deadlines and the UTC conversion are
 *     whatever production would have produced
 *   · a journey that already happened, rated by both sides and revealed — which is the only way
 *     `avg_rating_as_driver` becomes a number, and therefore the only way the stars on search
 *     results, match details and the group member list stop being `null`
 *   · a saved search and a commute request for the demo passenger, so those two screens are not
 *     empty either
 *
 * 🔒 Everything here is obviously fictional: Arabic given names, `example` email domains, and
 * phone numbers in a block nobody owns. No real person's data belongs in a seeder — it ends up in
 * screenshots, in bug reports, and in whatever database somebody copies to their laptop.
 *
 * Run it with:  php artisan db:seed --class=DemoDataSeeder --force
 */
class DemoDataSeeder extends Seeder
{
